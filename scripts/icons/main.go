// The elements a Lucide icon uses, and their attributes.
var allowed = map[string]bool{"path": true, "circle": true, "rect": true, "line": true, "polyline": true, "polygon": true, "ellipse": true}

type el struct {
	XMLName xml.Name
	Attrs   []xml.Attr `xml:",any,attr"`
}

type svg struct {
	Children []el `xml:",any"`
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: go run ./scripts/icons <lucide icons dir> <LICENSE> <version>")
		os.Exit(2)
	}
	dir, licenseFile, version := os.Args[1], os.Args[2], os.Args[3]
	license, err := os.ReadFile(licenseFile)
	if err != nil {
		fail(err)
	}
	keys := make([]string, 0, len(names))
	for k := range names {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by scripts/icons.sh from Lucide %s (https://lucide.dev). Do not edit by hand: add a name to\n", version)
	b.WriteString("// scripts/icons/main.go and run the script again. Each icon is a list of [element, attributes] drawn on a\n// 24 by 24 grid with a round stroke.\n//\n")
	for _, line := range strings.Split(strings.TrimSpace(string(license)), "\n") {
		b.WriteString(strings.TrimRight("// "+line, " ") + "\n")
	}
	b.WriteString("\nexport const ICON_SET = {\n")
	for _, k := range keys {
		raw, err := os.ReadFile(filepath.Join(dir, names[k]+".svg"))
		if err != nil {
			fail(fmt.Errorf("%s: %w", k, err))
		}
		var s svg
		if err := xml.Unmarshal(raw, &s); err != nil {
			fail(fmt.Errorf("%s: %w", names[k], err))
		}
		var parts []string
		for _, c := range s.Children {
			if !allowed[c.XMLName.Local] {
				fail(fmt.Errorf("%s: unexpected element <%s>", names[k], c.XMLName.Local))
			}
			attrs := map[string]string{}
			for _, a := range c.Attrs {
				attrs[a.Name.Local] = a.Value
			}
			j, _ := json.Marshal(attrs) // keys sorted, so the file is the same every time
			parts = append(parts, fmt.Sprintf("['%s', %s]", c.XMLName.Local, j))
		}
		fmt.Fprintf(&b, "  %s: [%s],\n", jsKey(k), strings.Join(parts, ", "))
	}
	b.WriteString("};\n")
	os.Stdout.WriteString(b.String())
}

func jsKey(k string) string {
	if strings.ContainsAny(k, "-") {
		return "'" + k + "'"
	}
	return k
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "icons:", err)
	os.Exit(1)
}
